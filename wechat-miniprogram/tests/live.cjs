// Opt-in integration smoke test. Creates and deletes ONLY its own uniquely named conversation.
const assert = require('node:assert/strict');
const https = require('node:https');
const { createPage } = require('./page-harness.cjs');
const base = process.env.PROTEIN_TEST_BASE || 'https://linpro.top';
const key = process.env.PROTEIN_TEST_KEY || '';
global.wx = {
  getStorageSync() { return base; }, setStorageSync() {},
  request(options) {
    let onHeaders = () => {}, onChunk = () => {};
    const task = https.request(options.url, { method: options.method || 'GET', headers: options.header }, response => {
      onHeaders({ statusCode: response.statusCode }); const chunks = [];
      response.on('data', chunk => { chunks.push(chunk); onChunk({ data: Uint8Array.from(chunk).buffer }); });
      response.on('end', () => {
        const buffer = Buffer.concat(chunks); let data = options.responseType === 'arraybuffer' ? Uint8Array.from(buffer).buffer : buffer.toString();
        if (options.responseType !== 'arraybuffer') { try { data = JSON.parse(data); } catch {} }
        options.success({ statusCode: response.statusCode, data });
      });
      response.on('error', error => options.fail({ errMsg: error.message }));
    });
    task.on('error', error => options.fail({ errMsg: error.message }));
    task.setTimeout(45000, () => task.destroy(new Error('integration test timeout')));
    if (options.data) task.write(JSON.stringify(options.data)); task.end();
    return { onHeadersReceived(fn) { onHeaders = fn; }, onChunkReceived(fn) { onChunk = fn; }, abort() { task.destroy(new Error('aborted')); } };
  }
};
const api = require('../utils/api');
const page = createPage(api, global.wx);
async function until(predicate, timeout = 60000) {
  const deadline = Date.now() + timeout;
  while (!predicate()) { if (Date.now() > deadline) throw new Error('timed out'); await new Promise(r => setTimeout(r, 100)); }
}
(async () => {
  page.data.key = key; await page.connect(); assert.equal(page.data.connected, true, page.data.error);
  console.log('PASS live model connection; models=' + page.data.models.length);
  const id = 'mobile-smoke-' + Date.now(); page.conversationId = id;
  try {
    page.data.input = '客户端自动化测试，请只回复：测试成功。'; page.send(); await until(() => !page.data.busy);
    assert.equal(page.data.error, ''); assert.ok(page.data.messages[1].content.length > 0);
    console.log('PASS live streamed Chinese reply');
    page.data.input = '这是同一对话的第二条消息，请只回复：续聊成功。'; page.send(); await until(() => !page.data.busy);
    assert.equal(page.data.error, ''); assert.equal(page.data.messages.length, 4);
    console.log('PASS live multi-turn continuation');
    await page.history(); assert.equal(page.data.error, '');
    const index = page.data.history.findIndex(c => c.id === id); assert.ok(index >= 0, 'saved conversation absent');
    await page.openConversation({ currentTarget: { dataset: { index } } });
    assert.equal(page.data.error, ''); assert.equal(page.data.messages.length, 4);
    console.log('PASS live saved history and message reload');
  } finally {
    // The ID is generated by this test; never delete existing user conversations.
    const response = await fetch(base + '/api/conversations?id=' + encodeURIComponent(id), { method: 'DELETE', headers: key ? { 'X-API-Key': key } : {} });
    console.log('Test conversation cleanup HTTP ' + response.status);
    assert.ok([204, 404].includes(response.status));
  }
})().catch(error => { console.error(error.message); process.exitCode = 1; });
